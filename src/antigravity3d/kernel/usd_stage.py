def _fmt(v: float) -> str:
    s = f"{round(v, 3) + 0.0:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def _vec(v) -> str:
    return "[" + ",".join(_fmt(x) for x in v) + "]"


def _triangulate(counts: np.ndarray, idx: np.ndarray) -> np.ndarray:
    if len(counts) and np.all(counts == 3):
        return idx.reshape(-1, 3).astype(np.int32)
    tris: list[tuple[int, int, int]] = []
    start = 0
    for c in counts:  # fan triangulation of convex polygons
        f = idx[start : start + c]
        tris.extend((f[0], f[i], f[i + 1]) for i in range(1, c - 1))
        start += c
    return np.asarray(tris, dtype=np.int32).reshape(-1, 3)


class _MeshRead(NamedTuple):
    prim: Usd.Prim
    mesh: MeshData
    local: np.ndarray  # (N, 3) float64 local-space points matching ``mesh.points`` (seam split folded)
    linear: np.ndarray = np.eye(3)  # 3x3 local-to-world linear part (compile_ir.facing: mirrored prims flip winding)


#: The ``UsdTransform2d`` a material on a shared atlas samples its maps through (child of the material prim).
MAP_REPEAT = "stRepeat"


def repeat_maps(stage: Usd.Stage, parts: Sequence[tuple[Usd.Prim, UVResult]]) -> list[Sdf.Path]:
    """Makes each material on a shared atlas sample its tileable maps as the package bakes them: one repeat every
    ``UVResult.repeat_px`` atlas px (``fast_ops.SWATCH_SPAN_PX`` at the target density, ``package._compose_atlas``).

    Without it a material's map spans the whole atlas on the stage (st in [0, 1]), so on an atlas that is not one
    repeat across (4096 x 2048, 1024 ...) the stage, its lookdev renders and the shipped package would show the
    surface at different scales. A ``UsdTransform2d`` (scale = atlas size / repeat) sits between the material's
    ``stReader`` and each of its ``UsdUVTexture`` shaders, whose wrapping is set to repeat. Authored in the current
    edit target (``author_uvs``: the UV overlay, cleared with the UVs). Returns the materials changed."""
    done: dict[Sdf.Path, tuple[float, float]] = {}
    for prim, res in parts:
        if not res.shared_atlas or not res.repeat_px:
            continue
        w, h = res.size
        scale = (w / res.repeat_px, h / res.repeat_px)
        if scale == (1.0, 1.0):
            continue  # one repeat spans the atlas: the map is sampled as the package ships it already
        mat, _ = UsdShade.MaterialBindingAPI(prim).ComputeBoundMaterial()
        if not mat or mat.GetPath() in done:
            continue
        reader = mat.GetPrim().GetChild("stReader")
        if not reader:
            continue
        out = UsdShade.Shader(reader).GetOutput("result")
        t2d = UsdShade.Shader.Define(stage, mat.GetPath().AppendChild(MAP_REPEAT))
        t2d.CreateIdAttr("UsdTransform2d")
        t2d.CreateInput("in", Sdf.ValueTypeNames.Float2).ConnectToSource(out)
        t2d.CreateInput("scale", Sdf.ValueTypeNames.Float2).Set(Gf.Vec2f(*scale))
        result = t2d.CreateOutput("result", Sdf.ValueTypeNames.Float2)
        for child in mat.GetPrim().GetChildren():
            tex = UsdShade.Shader(child)
            if not tex or tex.GetIdAttr().Get() != "UsdUVTexture":
                continue
            tex.CreateInput("st", Sdf.ValueTypeNames.Float2).ConnectToSource(result)
            for wrap in ("wrapS", "wrapT"):
                tex.CreateInput(wrap, Sdf.ValueTypeNames.Token).Set("repeat")
        done[mat.GetPath()] = scale
    return list(done)


class StageManager:
    def __init__(self, stage: Usd.Stage) -> None:
        self._stage = stage
        self._txs: list[tuple[str, Sdf.Layer]] = []  # bottom -> top; holds layers alive
        self._spatial: SpatialIndex | None = None
        self._spatial_listener = None
        self._export_layout: Sequence[UVResult] | None = None
        self._export_crease = CREASE_DEG  # shading crease of the authored export normals (see author_uvs)
        self._overlay: Sdf.Layer | None = None  # UV overlay, see module docstring
        # the layout of the package this design was opened from to be edited (fast_ops.KeepLayout), handed to every mesh
        # the export reads so its unwrap keeps what did not change; None for a new design
        self.keep_layout = None

    # --- construction ----------------------------------------------------------

    @classmethod
    def create(cls, path: Path, asset_name: str) -> StageManager:
        usd_boot.ensure_ready()  # stages are created from worker threads (the kit's pieces): never OpenUSD's first use
        stage = Usd.Stage.CreateNew(str(path))
        cls._init_structure(stage, SceneIR(asset_name=asset_name))
        stage.GetRootLayer().Save()
        return cls(stage)

    @classmethod
    def open(cls, path: Path) -> StageManager:
        """Opens a managed stage; a plain exported file is adopted from its stored IR."""
        usd_boot.ensure_ready()  # opened from worker threads too (sanitize's in-process path, the variant factory)
        stage = Usd.Stage.Open(str(path))
        if not stage.GetPrimAtPath(BASE):
            scene = read_ir(stage.GetDefaultPrim())
            if scene is None:
                raise ValueError(f"{path}: default prim has no '{IR_KEY}' customData")
            # Exported meshes may have been ingested from sources that are no
            # longer present. Adopt their composed geometry and binding targets.
            asset_path = stage.GetDefaultPrim().GetPath()
            flat = stage.Flatten()
            managed = Sdf.Layer.CreateAnonymous("adopted")
            if not Sdf.CopySpec(flat, asset_path, managed, BASE):
                raise ValueError(f"{path}: cannot adopt {asset_path}")
            copied = managed.GetPrimAtPath(BASE)
            copied.specifier = Sdf.SpecifierClass
            copied.ClearInfo("typeName")
            stage.GetRootLayer().TransferContent(managed)
            cls._init_structure(stage, scene)
        else:
            base = stage.GetPrimAtPath(BASE)
            legacy = any(
                prim.GetAttribute("agy:meshRef").Get() and not prim.IsA(UsdGeom.Mesh)
                for prim in Usd.PrimRange(base, Usd.PrimIsActive)
            )
            if legacy:
                # Upgrade marker-only references from v0.2. The caller controls disk
                # persistence by committing the returned ordinary transaction.
                manager = cls(stage)
                with manager.transaction("hydrate_mesh_refs"):
                    author_scene(stage, manager.base_ir(), root=BASE)
                return manager
        return cls(stage)

    @staticmethod
    def _init_structure(stage: Usd.Stage, scene: SceneIR) -> None:
        stage.SetEditTarget(stage.GetRootLayer())
        stage.CreateClassPrim(BASE)
        asset = UsdGeom.Xform.Define(stage, f"/{scene.asset_name}").GetPrim()
        Usd.ModelAPI(asset).SetKind(Kind.Tokens.component)
        asset.GetReferences().AddInternalReference(BASE)
        stage.SetDefaultPrim(asset)
        UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
        UsdGeom.SetStageMetersPerUnit(stage, 1.0)
        author_scene(stage, scene, root=BASE)

    # --- accessors -----------------------------------------------------------

    @property
    def stage(self) -> Usd.Stage:
        return self._stage

    @property
    def asset_prim(self) -> Usd.Prim:
        return self._stage.GetDefaultPrim()

    def mesh_ref_file(self, uri: str) -> Path:
        """The file a mesh_ref of this stage's scene names (``compile_ir.mesh_ref_file``)."""
        return mesh_ref_file(uri, self._stage.GetRootLayer().realPath)

    def scene_ir(self) -> SceneIR:
        """IR of the composed scene (including the selected variants)."""
        scene = read_ir(self.asset_prim)
        assert scene is not None, "managed stage lost its scene IR"
        return scene

    def base_ir(self) -> SceneIR:
        """IR of the plain scene, ignoring variant selections."""
        scene = read_ir(self._stage.GetPrimAtPath(BASE))
        assert scene is not None, "managed stage lost its base scene IR"
        return scene

    # --- transactions --------------------------------------------------------

    @property
    def tx_stack(self) -> list[str]:
        """Anonymous layer identifiers, oldest first (mirrors AssetSessionState.tx_stack)."""
        return [layer.identifier for _, layer in self._txs]

    @property
    def tx_ids(self) -> list[str]:
        return [tid for tid, _ in self._txs]

    def begin(self, tx_id: str | None = None) -> str:
        tx_id = tx_id or uuid.uuid4().hex[:12]
        if tx_id in self.tx_ids:
            raise ValueError(f"transaction {tx_id!r} already open")
        layer = Sdf.Layer.CreateAnonymous(f"tx_{tx_id}")
        self._stage.GetSessionLayer().subLayerPaths.insert(0, layer.identifier)
        self._txs.append((tx_id, layer))
        self._stage.SetEditTarget(layer)
        return tx_id

    def _index(self, tx_id: str) -> int:
        for i, (tid, layer) in enumerate(self._txs):
            if tx_id in (tid, layer.identifier):
                return i
        raise KeyError(f"unknown transaction {tx_id!r}")

    def rollback(self, tx_id: str | None = None, *, discard: bool = False) -> list[str]:
        """Remove the tx and everything above it. Return dropped ids, oldest first.

        Set discard only for private, rejected edits. Emptying those layers in
        the same Sdf change block reduces composition work. Ordinary undo keeps
        the contents of any layer pinned by another USD stage or client.
        """
        if not self._txs:
            raise RuntimeError("no open transaction to roll back")
        i = len(self._txs) - 1 if tx_id is None else self._index(tx_id)
        dropped = [(tid, layer.identifier) for tid, layer in self._txs[i:]]
        target = self._txs[i - 1][1] if i else self._stage.GetRootLayer()
        self._stage.SetEditTarget(target)
        sub = self._stage.GetSessionLayer().subLayerPaths
        with Sdf.ChangeBlock():  # one recomposition, including any derived UV opinions
            self._clear_overlay()
            prefix = [identifier for _, identifier in reversed(dropped)]
            if list(sub[:len(prefix)]) == prefix:
                del sub[:len(prefix)]
            else:  # preserve unrelated sublayers inserted by other USD clients
                for identifier in prefix:
                    sub.remove(identifier)
            if discard:
                for _, layer in self._txs[i:]:
                    layer.Clear()
            del self._txs[i:]
        return [tid for tid, _ in dropped]

    @contextmanager
    def transaction(self, tx_id: str | None = None) -> Iterator[str]:
        """Opens a tx; on exception it (and anything above it) is rolled back."""
        tid = self.begin(tx_id)
        try:
            yield tid
        except BaseException:
            if tid in self.tx_ids:
                self.rollback(tid)
            raise

    def _flatten_stack(self) -> Sdf.Layer:
        # Merges session layer + tx sublayers + root layer stack, keeping arcs
        # (reference to the base, variant sets) intact; not a composed flatten.
        return UsdUtils.FlattenLayerStack(self._stage)

    def commit_all(self) -> None:
        """Bakes every open tx into the root layer and saves it (if it is on disk)."""
        self._clear_overlay()  # derived data: baking it at composed paths would mask later base edits
        root = self._stage.GetRootLayer()
        flat = self._flatten_stack()
        session = self._stage.GetSessionLayer()
        with Sdf.ChangeBlock():
            session.subLayerPaths.clear()
            root.TransferContent(flat)
        self._txs.clear()
        self._stage.SetEditTarget(root)
        if not root.anonymous:
            root.Save()

    def flatten_to(self, path: Path) -> None:
        """Writes the baked layer stack (still a managed stage) without touching the session."""
        self._flatten_stack().Export(str(path))

    # --- edits ---------------------------------------------------------------

    def _check_scene(self, scene: SceneIR) -> None:
        if scene.asset_name != self.asset_prim.GetName():
            raise ValueError(f"asset_name {scene.asset_name!r} != stage asset {self.asset_prim.GetName()!r}")

    def _check_no_selection(self, ignore: str | None = None) -> None:
        vsets = self.asset_prim.GetVariantSets()
        sel = {n: vsets.GetVariantSelection(n) for n in vsets.GetNames() if n != ignore}
        if any(sel.values()):
            raise RuntimeError(f"variant selected {sel}; promote it or roll back before editing the base")

    def apply_ir(self, scene: SceneIR, tx_id: str | None = None) -> str:
        self._check_scene(scene)
        self._check_no_selection()
        self._clear_overlay()
        with self.transaction(tx_id) as tid:
            author_scene(self._stage, scene, root=BASE)
        return tid

    def apply_patch(self, patch: IRPatch, tx_id: str | None = None) -> str:
        self._check_no_selection()
        self._clear_overlay()
        with self.transaction(tx_id) as tid:
            base = self.base_ir()
            self._author_patch(base, patch, BASE, prev=base)  # BASE composes exactly the base IR just read
        return tid

    def _author_patch(self, base: SceneIR, patch: IRPatch, root: Sdf.Path, *, prev: SceneIR | None = None) -> None:
        """Applies ``patch`` to ``base`` and authors the result under ``root``.

        ``prev`` is the IR currently composed on ``root`` when the caller already holds it; ``author_scene`` then
        does not parse the embedded scene description a second time. Leave it None when ``root`` may compose
        something other than ``base`` (a variant being edited): ``author_scene`` reads it from the stage.
        """
        last = prev

        def resolve(current: SceneIR, op: ir.PlaceRelative) -> ir.Transform:
            # Earlier ops in the same tx can introduce geometry an anchor refers to.
            nonlocal last
            author_scene(self._stage, current, root=root, prev=last)
            last = current  # what ``root`` composes from here on
            return resolve_anchor(current, op, stage=self._stage)

        scene = ir.apply_patch(base, patch, anchor_resolver=resolve)
        author_scene(self._stage, scene, root=root, prev=last)

    # --- variants ------------------------------------------------------------

    def add_variant(
        self, set_name: str, variant: str, scene: SceneIR | IRPatch, tx_id: str | None = None
    ) -> str:
        """Authors ``scene`` as the delta of variant ``set_name=variant`` against the base."""
        if isinstance(scene, SceneIR):
            self._check_scene(scene)
        # The delta is taken against the composed scene, so no *other* set may be selected.
        self._check_no_selection(ignore=set_name)
        self._clear_overlay()
        prim = self.asset_prim
        with self.transaction(tx_id) as tid:
            vset = prim.GetVariantSets().AddVariantSet(set_name)
            if not vset.AddVariant(variant):
                raise ValueError(f"cannot add variant {set_name}={variant!r}")
            previous = vset.GetVariantSelection()
            vset.SetVariantSelection(variant)  # the variant must compose to be authored into
            layer = self._txs[-1][1]
            with vset.GetVariantEditContext(layer):
                if isinstance(scene, IRPatch):
                    self._author_patch(self.base_ir(), scene, prim.GetPath())
                else:
                    author_scene(self._stage, scene, root=prim.GetPath())
            if previous:
                vset.SetVariantSelection(previous)
            else:
                vset.ClearVariantSelection()
        return tid

    def list_variants(self, set_name: str) -> list[str]:
        vsets = self.asset_prim.GetVariantSets()
        return list(vsets.GetVariantSet(set_name).GetVariantNames()) if vsets.HasVariantSet(set_name) else []

    def _vset(self, set_name: str, variant: str) -> Usd.VariantSet:
        if variant not in self.list_variants(set_name):
            raise KeyError(f"unknown variant {set_name}={variant!r}")
        return self.asset_prim.GetVariantSets().GetVariantSet(set_name)

    def select_variant(self, set_name: str, variant: str, tx_id: str | None = None) -> str:
        vset = self._vset(set_name, variant)
        self._clear_overlay()
        with self.transaction(tx_id) as tid:
            vset.SetVariantSelection(variant)
        return tid

    def promote_variant(self, set_name: str, variant: str, tx_id: str | None = None) -> str:
        """Makes the variant's scene the plain base scene and removes the variant set."""
        vset = self._vset(set_name, variant)
        self._clear_overlay()
        with self.transaction(tx_id) as tid:
            vset.SetVariantSelection(variant)
            winner = self.scene_ir()
            # Other variants are deltas against the old base; drop the whole set.
            # (An authored "" selection does not hide weaker selections; a
            # listOp delete of the set name does.)
            spec = Sdf.CreatePrimInLayer(self._txs[-1][1], self.asset_prim.GetPath())
            spec.variantSetNameList.deletedItems = [*spec.variantSetNameList.deletedItems, set_name]
            if set_name in spec.variantSelections:
                del spec.variantSelections[set_name]
            author_scene(self._stage, winner, root=BASE)
        return tid

    # --- read-out ------------------------------------------------------------

    # --- UV overlay ----------------------------------------------------------

    def _clear_overlay(self) -> None:
        self._export_layout = None
        if self._overlay is not None and not self._overlay.empty:
            self._overlay.Clear()

    def _overlay_layer(self) -> Sdf.Layer:
        if self._overlay is None:
            self._overlay = Sdf.Layer.CreateAnonymous("uv_overlay")
            self._stage.GetSessionLayer().subLayerPaths.append(self._overlay.identifier)  # weakest session layer
        return self._overlay

    def _read_meshes(self) -> list[_MeshRead]:
        xc = UsdGeom.XformCache()
        out: list[_MeshRead] = []
        # which materials are opaque, read as the exporter reads them (run_export_pipeline's opaque_materials)
        from antigravity3d.kernel.coplanar import opaque_materials

        scene = read_ir(self.asset_prim)
        opaque = opaque_materials(scene) if scene is not None else None
        params: dict[Sdf.Path, Any] = {}  # per material: its parameters (MeshData.material), read once
        for prim in Usd.PrimRange(self.asset_prim):  # default predicate: active, defined, concrete
            if not prim.IsA(UsdGeom.Mesh):
                continue
            mesh = UsdGeom.Mesh(prim)
            pts = mesh.GetPointsAttr().Get()
            idx = mesh.GetFaceVertexIndicesAttr().Get()
            if not pts or not idx:
                continue
            counts = np.asarray(mesh.GetFaceVertexCountsAttr().Get(), dtype=np.int64)
            tris = _triangulate(counts, np.asarray(idx, dtype=np.int64))
            local = np.asarray(pts, dtype=np.float64)
            charts = prim.GetAttribute(UV_CHART_KEY).Get() if prim.HasAttribute(UV_CHART_KEY) else None
            charts = np.asarray(charts, dtype=np.int32) if charts is not None and len(charts) == len(tris) == len(counts) else None
            weld = prim.GetAttribute(UV_WELD_KEY).Get() if prim.HasAttribute(UV_WELD_KEY) else None
            if weld is not None and len(weld) == len(local) and len(tris) and tris.max() < len(local):
                # fold the xatlas seam split back: kernels see the pre-unwrap welded topology
                _, first, inv = np.unique(np.asarray(weld, dtype=np.int64), return_index=True, return_inverse=True)
                local = local[first]
                tris = inv.reshape(-1)[tris].astype(np.int32)
            m = np.array(xc.GetLocalToWorldTransform(prim))  # row-vector convention
            world = local @ m[:3, :3] + m[3, :3]
            tris = facing(tris, m[:3, :3]).astype(np.int32)  # a mirrored prim's baked mesh still faces out
            node = prim
            while node and not node.HasAttribute("agy:nodeId"):
                node = node.GetParent()
            node_id = node.GetAttribute("agy:nodeId").Get() if node else prim.GetName()
            collider = bool(node.GetAttribute("agy:collider").Get()) if node else True
            proxy = prim.GetAttribute(COLLIDER_PROXY_KEY).Get() if prim.HasAttribute(COLLIDER_PROXY_KEY) else None
            proxy = np.asarray(proxy, np.float64) @ m[:3, :3] + m[3, :3] if proxy is not None and len(proxy) >= 4 else None
            mat, _ = UsdShade.MaterialBindingAPI(prim).ComputeBoundMaterial()
            if mat and mat.GetPath() not in params:
                params[mat.GetPath()] = read_material(mat, double_sided=False)
            md = MeshData(
                node_id=node_id,
                prim_path=str(prim.GetPath()),
                points=world,
                triangles=tris,
                material_id=mat.GetPrim().GetName() if mat else None,
                collider=collider,
                uv_charts=charts,
                collider_points=proxy,
                opaque=None if opaque is None else (mat.GetPrim().GetName() if mat else None) in opaque,
                material=params.get(mat.GetPath()) if mat else None,
                keep_layout=self.keep_layout,
                run=read_run(prim, m),  # the part's run, carried as its collider proxy is (compile_ir._author_run)
                grain=read_grain(prim, m),
                double_sided=bool(mesh.GetDoubleSidedAttr().Get()),
            )
            out.append(_MeshRead(prim, md, local, m[:3, :3]))
        return out

    def extract_meshes(self) -> list[MeshData]:
        """Active composed meshes in world space (triangulated) for the geometry kernels.

        Seam-split vertices from an authored UV unwrap are folded back, so the result is the same
        before and after :meth:`author_uvs` (same triangles/positions; what is exported differs only
        by the seam duplicates).
        """
        return [r.mesh for r in self._read_meshes()]

    def author_uvs(self, results: Sequence[UVResult], *, normals: bool = True, crease_deg: float = CREASE_DEG) -> None:
        """Authors an unwrap into the working stage (see the module docstring on the overlay).

        ``results`` must be what ``unwrap_scene(self.extract_meshes(), ...)`` returned (same order).
        Each mesh gets the seam-split points/triangles of its :class:`UVResult`, ``primvars:st``
        (vertex interpolation) and faceVarying normals smoothed within ``crease_deg`` (an art direction's
        shading crease; the project's 40 degrees otherwise), so the composed stage, the validator and the
        exported package all agree with the GLB.
        """
        reads = self._read_meshes()
        if len(reads) != len(results):
            raise ValueError(f"{len(results)} UV results for {len(reads)} stage meshes (stale unwrap?)")
        for r, res in zip(reads, results):
            if r.mesh.node_id != res.node_id or len(r.mesh.triangles) != len(res.triangles):
                raise ValueError(f"UV result for {res.node_id!r} does not match stage mesh {r.mesh.prim_path}")
            if len(res.vmapping) and res.vmapping.max() >= len(r.local):
                raise ValueError(f"UV result for {res.node_id!r} indexes past the stage mesh's vertices")
        self._export_layout = None
        with Usd.EditContext(self._stage, self._overlay_layer()):
            for r, res in zip(reads, results):
                author_mesh_data(
                    r.prim, r.local[res.vmapping], facing(res.triangles, r.linear), res.uvs, weld_map=res.vmapping, normals=normals,
                    crease_deg=crease_deg,
                )
            repeat_maps(self._stage, [(r.prim, res) for r, res in zip(reads, results)])

        self._export_layout = results if normals else None
        self._export_crease = crease_deg

    def ensure_export_uvs(self, results: Sequence[UVResult], *, crease_deg: float = CREASE_DEG) -> None:
        """Bind this bundle's atlas even when the imported mesh already has source UVs (re-authored when the
        shading crease differs from the one the current export normals were written with)."""
        if self._export_layout is not results or self._export_crease != crease_deg:
            self.author_uvs(results, crease_deg=crease_deg)

    def has_uvs(self) -> bool:
        """True when every active mesh carries a ``primvars:st`` with a value per point."""
        meshes = [p for p in Usd.PrimRange(self.asset_prim) if p.IsA(UsdGeom.Mesh) and UsdGeom.Mesh(p).GetPointsAttr().Get()]
        for p in meshes:
            pv = UsdGeom.PrimvarsAPI(p).GetPrimvar("st")
            v = pv.Get() if pv else None
            if v is None or len(v) != len(UsdGeom.Mesh(p).GetPointsAttr().Get()):
                return False
        return bool(meshes)

    def _invalidate_spatial(self, notice, sender) -> None:
        self._spatial = None
        self._spatial_listener.Revoke()
        self._spatial_listener = None

    def _spatial_index(self) -> SpatialIndex:
        if self._spatial is not None:
            return self._spatial
        time = Usd.TimeCode.Default()
        xc = UsdGeom.XformCache(time)
        records: dict[str, PrimInfo] = {}
        for prim in Usd.PrimRange(self.asset_prim):
            if not prim.IsA(UsdGeom.Mesh):
                continue
            mesh = UsdGeom.Mesh(prim)
            counts = mesh.GetFaceVertexCountsAttr().Get()
            if not counts:
                continue
            extent = mesh.GetExtentAttr().Get()
            if extent is None:
                extent = UsdGeom.Boundable.ComputeExtentFromPlugins(mesh, time)
            if extent is None or len(extent) != 2:
                continue
            box = Gf.BBox3d(Gf.Range3d(Gf.Vec3d(extent[0]), Gf.Vec3d(extent[1])),
                            xc.GetLocalToWorldTransform(prim)).ComputeAlignedRange()
            owner = prim
            while owner and not owner.HasAttribute("agy:nodeId"):
                owner = owner.GetParent()
            nid = owner.GetAttribute("agy:nodeId").Get() if owner else str(prim.GetPath())
            lo, hi = tuple(box.GetMin()), tuple(box.GetMax())
            tris = int(np.maximum(0, np.asarray(counts) - 2).sum())
            material, _ = UsdShade.MaterialBindingAPI(prim).ComputeBoundMaterial()
            mat = material.GetPrim().GetName() if material else None
            if prev := records.get(nid):
                lo = tuple(np.minimum(lo, prev.bounds_min))
                hi = tuple(np.maximum(hi, prev.bounds_max))
                tris += prev.tris
                mat = mat if mat == prev.material_id else None
            records[nid] = PrimInfo(nid, lo, hi, tris, mat, None)
        self._spatial = SpatialIndex.from_bounds(list(records.values()))
        # Register only while an index exists. Raw USD edits and variant switches also invalidate it.
        self._spatial_listener = Tf.Notice.Register(Usd.Notice.ObjectsChanged, self._invalidate_spatial, self._stage)
        return self._spatial

    def query_region(self, bounds_min, bounds_max, *, limit: int = 32, max_chars: int = 1200,
                     depth: int | None = None) -> str:
        """Bounded octree navigation over the composed scene. Bounds are world-space metres."""
        if not 1 <= limit <= 256 or not 1 <= max_chars <= 4096:
            raise ValueError("limit must be 1..256 and max_chars must be 1..4096")
        return self._spatial_index().query_region(bounds_min, bounds_max, depth, limit).to_text(max_chars)

    def manifest(self, *, max_chars: int | None = None) -> str:
        """Terse per-node summary of the composed scene for LLM context."""
        scene = self.scene_ir()
        root = self.asset_prim.GetPath()
        paths = node_paths(scene, root)
        index = self._spatial_index()
        tris = dict(zip(index.ids, index.tris))
        cache = UsdGeom.BBoxCache(Usd.TimeCode.Default(), [UsdGeom.Tokens.default_], useExtentsHint=False)

        def bbox(path: Sdf.Path) -> str:
            rng = cache.ComputeWorldBound(self._stage.GetPrimAtPath(path)).ComputeAlignedRange()
            return "-" if rng.IsEmpty() else f"{_vec(rng.GetMin())}..{_vec(rng.GetMax())}"

        vsets = self.asset_prim.GetVariantSets()
        sel = " ".join(f"{n}={vsets.GetVariantSelection(n)}" for n in vsets.GetNames() if vsets.GetVariantSelection(n))
        head = (
            f"# {scene.asset_name} nodes={len(scene.nodes)} mats={len(scene.materials)} "
            f"tris={sum(tris.values())} bbox={bbox(root)}" + (f" variant {sel}" if sel else "")
        )
        if max_chars is not None and len(head) >= max_chars:
            return head[:max(0, max_chars)]
        lines = [head]
        used = len(head)
        for i, n in enumerate(scene.nodes):
            line = f"{n.id} {n.kind} {bbox(paths[n.id])} tris={tris.get(n.id, 0)} mat={n.material_id or '-'}"
            trailer = f"... +{len(scene.nodes) - i} nodes"
            reserve = len(trailer) + 1 if i + 1 < len(scene.nodes) else 0
            if max_chars is not None and used + 1 + len(line) + reserve > max_chars:
                if used + 1 + len(trailer) <= max_chars:
                    lines.append(trailer)
                break
            lines.append(line)
            used += len(line) + 1
        return "\n".join(lines)

    def export_layer(self) -> Sdf.Layer:
        """The composed scene (current variant selections, UV overlay included) as one anonymous
        layer, without the internal base class prim. Fresh on every call; safe to edit.

        Flattened without USD's source-file comment: that comment is the working stage's absolute path, which
        would put a local path into every shipped file and make two exports of the same scene differ."""
        flat = self._stage.Flatten(addSourceFileComment=False)
        edit = Sdf.BatchNamespaceEdit()
        edit.Add(BASE, Sdf.Path.emptyPath)  # the base class is an authoring detail
        if not flat.Apply(edit):
            raise RuntimeError("failed to strip base class from export")

        def clear_redundant(spec: Sdf.PrimSpec) -> None:
            if spec.HasInfo("active") and spec.active:
                spec.ClearActive()
            if spec.nameChildrenOrder:  # Flatten writes the children in their composed order and keeps the statement too
                spec.nameChildrenOrder = []
            for child in spec.nameChildren:
                clear_redundant(child)

        # What only the builds that preceded this design left in the one-layer file, and no reader needs: a part a
        # later design dropped is deactivated and, when brought back, activated again (`active = true`), and a design
        # that put a part between existing ones carries the children reorder that did it (see
        # compile_ir._order_children). Both made the USD and USDZ of one design differ with the session's history.
        for top in flat.rootPrims:
            clear_redundant(top)
        return flat

    def export(self, path: Path) -> None:
        """Writes the composed scene (current variant selections) as .usda/.usdc/.usdz."""
        path = Path(path)
        suffix = path.suffix.lower()
        if suffix not in (".usda", ".usdc", ".usdz"):
            raise ValueError(f"unsupported export format {suffix!r}")
        flat = self.export_layer()
        if suffix != ".usdz":
            flat.Export(str(path))
            return
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / f"{path.stem}.usdc"
            flat.Export(str(src))
            if not create_usdz(src, path):
                raise RuntimeError(f"usdz packaging failed for {path}")
