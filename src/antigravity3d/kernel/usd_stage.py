"""OpenUSD stage manager: transactional sublayers + variant-set branches.

Layout of a managed stage::

    root layer (on disk)          committed state
      class /__agy_base           the plain scene: nodes, Looks, customData IR
      def Xform /<asset>          default prim, kind=component,
                                  references </__agy_base>, variant sets
    session layer
      subLayerPaths = [tx_n, ..., tx_1]   anonymous per-edit delta layers

Every edit authors into a fresh anonymous layer inserted as the strongest
session sublayer, so rollback is removing a sublayer path. The plain scene
lives under an internal *reference* (not directly on the default prim)
because USD's LIVRPS ordering makes local opinions stronger than variants:
behind a reference, a variant can override any base node, so a variant only
has to hold the delta of its proposal against the base.

UV overlay: unwrapped UVs (the unwrap splits vertices at chart seams) are authored by
:meth:`StageManager.author_uvs` into one dedicated anonymous *overlay* layer
that sits at the bottom of the session sublayers, at the *composed* prim
paths. Local opinions beat both the base reference and any selected variant,
so the overlay is correct for whatever is composed right now (including a
selected variant). The price is that it masks later base edits, so every
method that changes composition or geometry (apply_*, variants, rollback,
commit_all) clears it first: UVs are derived data and are regenerated by the
export pipeline. The overlay is deliberately *not* a numbered transaction, so
it never shows up in ``tx_stack`` and ``undo`` still undoes the user's last
edit. :meth:`extract_meshes` folds the seam split back, so kernels always see
the pre-unwrap welded topology, and unwrapping twice is idempotent. Primitive meshes also carry
``agy:uvChart`` (their exact developable chart per triangle, authored by compile_ir); the overlay keeps
triangle order, so :meth:`extract_meshes` returns the same ``MeshData.uv_charts`` before and after.
"""

