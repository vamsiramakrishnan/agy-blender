"""What made each file of a package: the manifest's ``provenance`` record (``schema_version`` 4).

A game developer has to answer a store's AI-content disclosure ("is any shipped content generated, by what, from
what?") and a reviewer has to trust a file, so the manifest says, for every file it lists, which sources it derives
from and which deterministic steps got it there, and for every source who made it:

* ``sources``: the roots. ``design`` (the scene: authored by a model, a deterministic template, an agent in a native
  session, an asset script, or supplied by the user), ``albedo:<material>`` (a generated image), ``ortho`` (a generated blueprint),
  ``supplied:<name>`` (a file the user gave, by hash), ``style_anchor`` (a reference image the user gave).
* ``files``: per shipped file ``derived_from`` (source ids and other shipped files), ``steps`` (deterministic code
  that transformed them) and, resolved through the graph, ``generated_content`` (True: a model made part of it;
  False: no; None: a source of it is unrecorded) and ``generated_by`` (model ids).
* ``generated_content``, ``models``, ``offline_fakes``, ``unrecorded``: the same answers for the package.

Identities and hashes only: no times, no costs, no paths on the author's machine, and nothing that differs between a
run that paid for a model answer and a rerun that took it from the design record or the image cache. Two exports
of one scene stay byte-identical (the package's contract), manifest included. The model ids are those the service
was asked for (never the ``(cached)`` mark of a cache hit); an image made by the offline stand-in is recorded as that
stand-in and is not counted as generated by a model.

The writers of a package call :func:`build` (structure, derived steps, supplied meshes); the pipeline that knows who
authored and generated adds those facts with :func:`set_design` / :func:`set_image` and calls :func:`finalize`.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Iterable, Mapping
from pathlib import Path
from typing import Any

VERSION = 1
SCHEMA_VERSION = 4  # the manifest schema_version whose contract has this record

#: source kinds that count as content a model generated. ``script``: the design was built by an asset script
#: (``run_build``), which the conversation's agent wrote, so it counts as that agent's work exactly as a design it edited
#: through apply_scene_ir does; ``script_output``: a mesh file that script made (not a file the user supplied).
MODEL_KINDS = frozenset({"model_authored", "model_authored_in_session", "model_generated_image", "script", "script_output"})
#: source kinds that are known not to be model-generated (a stand-in, a template, a file the user gave)
NON_MODEL_KINDS = frozenset({"template", "offline_fake_image", "user_supplied"})

_NORMAL_ROLES = {"orm": ("derive_pbr",), "normal": ("derive_pbr",)}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def sha256_json(value: Any) -> str:
    """Hash of a JSON-able value in canonical form (sorted keys, no whitespace)."""
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


def supplied_meshes(scene: Any) -> dict[str, dict[str, Any]]:
    """``{"supplied:<file name>": {...}}`` for each ``mesh_ref`` node of ``scene`` whose file exists: the user's file,
    by hash. The file's name, never its directory."""
    out: dict[str, dict[str, Any]] = {}
    for node in getattr(scene, "nodes", ()) or ():
        if getattr(node, "kind", None) != "mesh_ref":
            continue
        raw = (getattr(node, "params", None) or {}).get("path")
        path = Path(str(raw)) if raw else None
        if path is not None and path.is_file():
            out[f"supplied:{path.name}"] = {"kind": "user_supplied", "sha256": sha256_file(path), "bytes": path.stat().st_size}
    return out


def _texture_steps(rec: Mapping[str, Any], styled: bool) -> list[str]:
    role = rec.get("role")
    steps = ["prepare_albedo", *_NORMAL_ROLES.get(str(role), ())]
    if role == "normal" and rec.get("converted"):
        steps.append("normal_convention_flip")
    if styled:
        steps.append("art_direction_finish_map")
    return steps


def build(data: Mapping[str, Any], *, supplied: Mapping[str, Mapping[str, Any]] | None = None, styled: bool = False,
          asset: str | None = None) -> dict[str, Any]:
    """The record for a package manifest ``data`` (its ``files`` and ``textures`` as written): every source that the
    writer cannot know is ``unrecorded`` until :func:`set_design` / :func:`set_image` say otherwise.

    ``supplied``: :func:`supplied_meshes` of the scene. ``styled``: an art direction finished the maps."""
    asset = asset or str(data.get("asset"))
    sources: dict[str, Any] = {"design": {"kind": "unrecorded"}}
    sources.update({k: dict(v) for k, v in (supplied or {}).items()})
    tex_files: dict[str, dict[str, Any]] = {}
    for rec in data.get("textures") or []:
        mat = rec.get("material")
        sources.setdefault(f"albedo:{mat}", {"kind": "unrecorded"})
        for rel in dict.fromkeys((rec.get("path"), rec.get("usd_path"))):
            if rel:
                entry = tex_files.setdefault(rel, {"derived_from": [f"albedo:{mat}"], "steps": _texture_steps(rec, styled)})
                if rec.get("role") == "normal" and rel != rec.get("usd_path") and "normal_convention_flip" not in entry["steps"]:
                    entry["steps"].append("normal_convention_flip")
    textures = sorted(tex_files)
    base = ["design", *sorted(supplied or {})]
    files: dict[str, Any] = {}
    for rel in data.get("files") or []:
        if rel == "manifest.json":
            continue
        if rel in tex_files:
            files[rel] = tex_files[rel]
        elif rel == f"{asset}_colliders.glb":
            files[rel] = {"derived_from": list(base), "steps": ["collider_decomposition", "glb_writer"]}
        elif rel.endswith(".usd"):
            files[rel] = {"derived_from": [*base, *textures], "steps": ["usd_export", "lod_generation", "uv_unwrap"]}
        elif rel.endswith(".usdz"):
            files[rel] = {"derived_from": [f"{asset}.usd", *textures], "steps": ["usdz_pack"]}
        elif rel.endswith(".glb"):
            lod = re.search(r"_LOD\d+\.glb$", rel)
            files[rel] = {"derived_from": [*base, *textures], "steps": ["glb_writer", *(["lod_generation"] if lod else []),
                                                                        "contact_face_removal", "uv_unwrap"]}
        elif rel == data.get("inspector"):
            files[rel] = {"derived_from": [f"{asset}.glb", *textures], "steps": ["inspector_build"]}
        else:  # a file this module has no rule for (Roblox surface maps, ...): everything it could be made from
            files[rel] = {"derived_from": [*base, *textures], "steps": ["package_writer"]}
    return {"version": VERSION, "sources": sources, "files": files}


def set_design(prov: dict[str, Any], record: Mapping[str, Any]) -> None:
    """Say who made the scene (``kind``: model_authored | model_authored_in_session | template | user_supplied)."""
    prov["sources"]["design"] = dict(record)


def set_image(prov: dict[str, Any], source: str, record: Mapping[str, Any]) -> None:
    """Say who made a generated image (``source``: ``albedo:<material>`` or ``ortho``); a source the package does not
    use (a material that was not shipped) is ignored."""
    if source in prov["sources"] or source == "ortho":
        prov["sources"][source] = dict(record)


def add_file(prov: dict[str, Any], rel: str, derived_from: Iterable[str], steps: Iterable[str]) -> None:
    """A file added to the package after :func:`build` (a render, the FBX, the blueprint)."""
    prov["files"][rel] = {"derived_from": list(derived_from), "steps": list(steps)}


def add_added_files(prov: dict[str, Any], data: Mapping[str, Any]) -> None:
    """Entries for files the pipeline put into ``data['files']`` after the writer (blueprint, engine and DCC renders, the
    FBX); a listed file that has none yet is derived from the package's own files."""
    asset = str(data.get("asset"))
    textures = sorted(r for r in prov["files"] if r.startswith("textures/"))
    for rel in data.get("files") or []:
        if rel == "manifest.json" or rel in prov["files"]:
            continue
        if rel == "ortho.png":
            prov["sources"].setdefault("ortho", {"kind": "unrecorded"})  # the pipeline that made it says who
            add_file(prov, rel, ["ortho"], [])
        elif rel.endswith(".fbx"):
            add_file(prov, rel, [f"{asset}.glb", *textures], ["blender_fbx_export"])
        elif rel.endswith(".png"):  # the engine and DCC renders of the package
            add_file(prov, rel, [f"{asset}.glb", *textures], ["render"])
        else:
            add_file(prov, rel, ["design", *textures], ["package_writer"])


def _kind(source: Mapping[str, Any]) -> str:
    return str(source.get("kind", "unrecorded"))


def _reach(prov: Mapping[str, Any], rel: str, seen: set[str] | None = None) -> set[str]:
    """The source ids a file derives from, through the files it derives from."""
    seen = seen if seen is not None else set()
    out: set[str] = set()
    for dep in (prov["files"].get(rel) or {}).get("derived_from", []):
        if dep in prov["files"]:
            if dep not in seen:
                seen.add(dep)
                out |= _reach(prov, dep, seen)
        else:
            out.add(dep)
    return out


def finalize(prov: dict[str, Any], data: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Resolve ``generated_content`` / ``generated_by`` per file and for the package; deterministic (sorted)."""
    if data is not None:
        listed = set(data.get("files") or [])
        for rel in [r for r in prov["files"] if r not in listed]:  # a file taken out of the package (a dropped FBX)
            del prov["files"][rel]
        add_added_files(prov, data)
    sources = prov["sources"]
    everything: set[str] = set()
    for rel, entry in prov["files"].items():
        ids = _reach(prov, rel)
        everything |= ids
        kinds = {i: _kind(sources.get(i, {})) for i in ids}
        gen = [i for i, k in kinds.items() if k in MODEL_KINDS]
        unknown = [i for i, k in kinds.items() if k not in MODEL_KINDS and k not in NON_MODEL_KINDS]
        entry["generated_content"] = True if gen else (None if unknown else False)
        entry["generated_by"] = sorted({str(sources[i].get("model") or "unknown model") for i in gen})
    gens = [e["generated_content"] for e in prov["files"].values()]
    prov["generated_content"] = True if any(g is True for g in gens) else (None if any(g is None for g in gens) else False)
    prov["models"] = sorted({m for e in prov["files"].values() for m in e["generated_by"]})
    prov["offline_fakes"] = any(_kind(s) == "offline_fake_image" for s in sources.values())
    prov["unrecorded"] = sorted(i for i in everything if _kind(sources.get(i, {})) == "unrecorded")
    prov["files"] = {k: prov["files"][k] for k in sorted(prov["files"])}
    prov["sources"] = {k: sources[k] for k in sorted(sources)}
    return prov


def problems(man: Mapping[str, Any]) -> list[str]:
    """What is inconsistent in a manifest's record (for ``validate_package``): a listed file without an entry, an
    entry for a file that is not listed, a dependency that is neither a source nor a listed file, a resolved answer
    that is not what the graph gives."""
    prov = man.get("provenance")
    if not isinstance(prov, dict) or not isinstance(prov.get("sources"), dict) or not isinstance(prov.get("files"), dict):
        return ["manifest has no provenance record"]
    out: list[str] = []
    listed = {f for f in man.get("files") or [] if f != "manifest.json"}
    for rel in sorted(listed - set(prov["files"])):
        out.append(f"{rel}: no provenance entry")
    for rel in sorted(set(prov["files"]) - listed):
        out.append(f"{rel}: provenance entry for a file the manifest does not list")
    for rel, entry in prov["files"].items():
        for dep in entry.get("derived_from", []):
            if dep not in prov["sources"] and dep not in prov["files"]:
                out.append(f"{rel}: derived from {dep!r}, which is neither a source nor a file")
    if not out:
        import copy
        again = finalize(copy.deepcopy(prov))
        for key in ("generated_content", "models", "offline_fakes", "unrecorded"):
            if again.get(key) != prov.get(key):
                out.append(f"provenance.{key} is {prov.get(key)!r}, the record gives {again.get(key)!r}")
        for rel, entry in prov["files"].items():
            if again["files"][rel].get("generated_content") != entry.get("generated_content"):
                out.append(f"{rel}: generated_content is {entry.get('generated_content')!r}, the record gives "
                           f"{again['files'][rel].get('generated_content')!r}")
    return out
